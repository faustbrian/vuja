func namedChatboxColorTargets(colors *ChatboxColorsConfig) map[string]*string {
	names := []string{
		"directory", "directory-root", "directory-read-only", "git-branch", "git-status", "git-clean",
		"git-operation", "git-conflicts", "git-staged", "git-modified", "git-renamed", "git-untracked",
		"git-ahead", "git-behind", "git-added", "git-deleted", "git-stash", "git-lines-added",
		"git-lines-deleted", "session", "session-warning", "session-critical", "contexts", "environment",
		"version-mismatch", "package", "stale", "jobs", "jobs-stopped", "exit-neutral", "exit-success",
		"exit-failure", "duration", "duration-fast", "duration-average", "duration-slow", "load-low",
		"load-average", "load-high", "load-critical", "laravel", "php", "composer", "python", "ruby",
		"elixir", "go", "node", "bun", "rust", "docker", "docker-compose", "cpu", "memory",
	}
	targets := chatboxColorTargets(colors)
	result := make(map[string]*string, len(names))
	for index, name := range names {
		result[name] = targets[index]
	}
	return result
}
